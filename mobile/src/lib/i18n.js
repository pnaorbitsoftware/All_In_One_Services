export function normalizeLanguage(language) {
  return dictionaries[language] ? language : DEFAULT_LANGUAGE;
}

export function translate(language, key, fallback) {
  const normalized = normalizeLanguage(language);
  return dictionaries[normalized]?.[key] || dictionaries[DEFAULT_LANGUAGE][key] || fallback || key;
}

export function createTranslator(language) {
  const normalized = normalizeLanguage(language);
  return (key, fallback) => translate(normalized, key, fallback);
}
