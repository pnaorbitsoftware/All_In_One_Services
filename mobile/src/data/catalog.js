export function iconForCategory(category) {
  return categoryIcons[category] || "briefcase-check-outline";
}

export function imageForService(service = {}) {
  const name = service.name || service.title || "";
  const category = service.category || "";
  return serviceImages[name] || serviceImages[category] || categoryImages[category] || categoryImages.Cleaning;
}

export function normalizeProvider(provider) {
  const category = provider.category || "Cleaning";
  const profileImage = typeof provider.image === "string" ? provider.image.trim() : "";

  return {
    id: provider._id || provider.providerCode || `${provider.name}-${category}`,
    providerId: provider._id || "",
    name: provider.name || "Service provider",
    category,
    location: provider.location || "Nearby",
    rating: provider.rating || 0,
    reviews: provider.reviews || 0,
    responseTime: provider.responseTime || "~1 hr",
    price: provider.price || "Contact for price",
    phone: provider.phone || "",
    email: provider.email || "",
    description: provider.description || `${provider.name || "This provider"} handles ${category} services.`,
    about: provider.about || provider.description || `${category} support for local homes.`,
    features: provider.features?.length ? provider.features : [category, "On-site visit", "Work inspection"],
    profileImage,
    image: profileImage || imageForService({ name: provider.name, category }),
    icon: iconForCategory(category),
  };
}

export function buildMarketplace(providers = []) {
  const map = new Map(
    fallbackServices.map((service) => [
      `${service.name}-${service.category}`,
      {
        ...service,
        providerId: "",
        icon: iconForCategory(service.category),
        profileImage: "",
        image: imageForService(service),
      },
    ])
  );

  providers.forEach((provider) => {
    const normalized = normalizeProvider(provider);
    map.set(`${normalized.name}-${normalized.category}`, normalized);
  });

  return [...map.values()];
}
